def main():
    out = [HEADER]
    for f in ["css/styles.css", "css/app.css"]:
        for media, sel, body in rules(open(f, encoding="utf-8").read()):
            t = transform(sel, body)
            if not t:
                continue
            rule = f"{sel} {{ {t} }}"
            out.append(f"{media} {{ {rule} }}" if media else rule)
    out.append(HAND)
    open("css/theme-paper.css", "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(len(out) - 1, "generated rules")


if __name__ == "__main__":
    main()
