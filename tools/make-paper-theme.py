"""Generate css/theme-paper.css: a light, graph-paper version of the MNM site.

The original dark theme stays untouched in styles.css/app.css. This file only
overrides it, so removing the <link> to theme-paper.css restores the old look.
Re-run after editing styles.css/app.css:  python3 tools/make-paper-theme.py
"""
import re

NAVY = "#0A2A57"
SKIP = re.compile(r"^(\.btn(\b|::after|:hover)|\.btn-sm|\.btn-xl|::selection|\.count|\.avatar|\.cursor|\.tog input::after|\.btn > span|\.btn b)")
DARK_PANEL = re.compile(r"rgba\(\s*(8,\s*20,\s*44|10,\s*22,\s*48|5,\s*15,\s*34)\s*,\s*[\d.]+\s*\)")


def rules(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    out, depth, buf, media = [], 0, "", None
    i = 0
    while i < len(css):
        ch = css[i]
        buf += ch
        if ch == "{":
            depth += 1
            if depth == 1 and buf.strip().startswith("@media"):
                media = buf.strip()[:-1].strip(); buf = ""
            elif depth == 1 and buf.strip().startswith("@"):
                # keyframes etc: skip whole block
                j, d = i + 1, 1
                while d:
                    d += {"{": 1, "}": -1}.get(css[j], 0); j += 1
                i = j; buf = ""; depth = 0; continue
        elif ch == "}":
            depth -= 1
            if depth == 0 and media is not None and buf.strip() == "}":
                media = None; buf = ""
            elif (media is None and depth == 0) or (media is not None and depth == 1):
                sel, _, body = buf.strip().partition("{")
                out.append((media, sel.strip(), body.rstrip("}").strip()))
                buf = ""
        i += 1
    return out


def transform(sel, body):
    if SKIP.match(sel):
        return None
    orig = body
    # swap white-on-navy pairs (chips, pills, light buttons) -> navy-on-white
    body = body.replace("#fff", "\0N").replace("var(--navy)", "#fff").replace("\0N", "var(--navy)")
    body = DARK_PANEL.sub("rgba(255, 255, 255, .88)", body)
    body = re.sub(r"rgba\(\s*255\s*,\s*255\s*,\s*255\s*,\s*([\d.]+)\s*\)",
                  lambda m: f"rgba(10, 42, 87, {min(float(m.group(1)) * 1.1, .9):.3g})", body)
    body = re.sub(r"rgba\(\s*0\s*,\s*0\s*,\s*0\s*,\s*([\d.]+)\s*\)",
                  lambda m: f"rgba(10, 42, 87, {float(m.group(1)) * .35:.3g})", body)
    body = body.replace("#040b1a", "var(--bg)").replace("#0b1b38", "#ffffff")
    body = body.replace("#cfd9ea", "#33476b").replace("#dfe7f3", NAVY).replace("color-scheme: dark", "color-scheme: light")
    body = body.replace("linear-gradient(180deg, #fff, #8fa7cf)", f"linear-gradient(180deg, {NAVY}, #3b6fd6)")
    if body == orig:
        return None
    # keep only declarations that changed
    decl = lambda b: [d.strip() for d in re.split(r";(?![^(]*\))", b) if d.strip()]
    o, n = decl(orig), decl(body)
    changed = [d for d in n if d not in o]
    return "; ".join(changed) + ";" if changed else None


